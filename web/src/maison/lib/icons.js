export const icon = (name) => icons[name] ?? mdiLightbulbOutline;

/** WMO weather code (Open-Meteo) → icon and words (said in the house's
 *  language when called, not when the module loads). */
export function weatherOf(code, day = true) {
  const c = Number(code);
  if (!Number.isFinite(c)) return { icon: mdiWeatherCloudy, label: t('commun.meteo.indisponible') };
  if (c === 0) return { icon: day ? mdiWeatherSunny : mdiWeatherNight, label: t('commun.meteo.degage') };
  if (c <= 2) return { icon: day ? mdiWeatherPartlyCloudy : mdiWeatherNight, label: t('commun.meteo.quelques_nuages') };
  if (c === 3) return { icon: mdiWeatherCloudy, label: t('commun.meteo.couvert') };
  if (c <= 48) return { icon: mdiWeatherFog, label: t('commun.meteo.brouillard') };
  if (c <= 57) return { icon: mdiWeatherRainy, label: t('commun.meteo.bruine') };
  if (c <= 64 || (c >= 80 && c <= 81)) return { icon: mdiWeatherRainy, label: t('commun.meteo.pluie') };
  if (c <= 67 || c === 82) return { icon: mdiWeatherPouring, label: t('commun.meteo.forte_pluie') };
  if (c <= 77 || c === 85 || c === 86) return { icon: mdiWeatherSnowy, label: t('commun.meteo.neige') };
  return { icon: mdiWeatherLightningRainy, label: t('commun.meteo.orage') };
}
